/// Rows asked for per page. The ports clamp to 1000.
const PAGE: u32 = 1000;
/// Pages read before giving up. Bounds a listing that never ends (a broken port) at a hundred
/// million rows, far beyond `MAX_VERSIONS`.
const MAX_PAGES: usize = 10_000;
/// Most versions of one artifact a generated document lists, the cap the parser applies too.
const MAX_LISTED: usize = crate::metadata::MAX_VERSIONS;

const XML: &str = "application/xml";

impl MavenHandler {
    /// `GET` and `HEAD` on a hosted repository.
    pub(crate) async fn hosted_get(
        &self,
        cx: &FormatContext,
        req: &ArtifactRequest,
        parsed: Option<MavenPath>,
    ) -> Result<Response<Body>, FormatError> {
        match parsed {
            None => cx.hosted().download(req).await,
            Some(MavenPath::Artifact {
                file,
                checksum: None,
            }) => hosted_artifact(cx, req, &file).await,
            Some(MavenPath::Artifact {
                file,
                checksum: Some(algo),
            }) => hosted_artifact_checksum(cx, req, &file, algo).await,
            Some(MavenPath::Metadata { level, checksum }) => {
                hosted_metadata(cx, req, &level, checksum).await
            }
        }
    }

    /// `PUT`: an artifact file, a checksum file, or metadata.
    pub(crate) async fn hosted_put(
        &self,
        cx: &FormatContext,
        req: &ArtifactRequest,
        parsed: MavenPath,
        body: Body,
    ) -> Result<Response<Body>, FormatError> {
        match parsed {
            MavenPath::Artifact {
                file,
                checksum: None,
            } => put_artifact(cx, req, &file, body).await,
            MavenPath::Artifact {
                file,
                checksum: Some(algo),
            } => put_artifact_checksum(cx, req, &file, algo, body).await,
            MavenPath::Metadata { level, checksum } => {
                self.put_metadata(cx, req, &level, checksum, body).await
            }
        }
    }

    /// Metadata is generated by the server, so an uploaded `maven-metadata.xml` is checked and
    /// dropped. `mvn deploy` sends it after every artifact (merged with what it read from the
    /// repository), and answering 201 keeps every client working while the repository stays
    /// the only author of the document. It is still parsed: a client that uploads garbage or an
    /// XXE document should hear about it at deploy time, and the parser is what the
    /// tests of the negative requirements exercise.
    async fn put_metadata(
        &self,
        cx: &FormatContext,
        req: &ArtifactRequest,
        level: &MetadataLevel,
        checksum: Option<ChecksumAlgo>,
        body: Body,
    ) -> Result<Response<Body>, FormatError> {
        refuse_when_read_only(cx)?;
        if let MetadataLevel::Version { version, .. } = level {
            enforce_write_policy(cx.repository(), version)?;
        }
        if let Some(algo) = checksum {
            read_checksum_file(req, body, algo).await?;
            return Ok(status_only(StatusCode::CREATED));
        }
        let cap = self.config.max_metadata_bytes;
        if req
            .head
            .content_length()
            .is_some_and(|declared| declared > cap)
        {
            return Err(FormatError::PayloadTooLarge { limit: cap });
        }
        let bytes = read_bounded(body, cap).await.map_err(|error| match error {
            BoundedReadError::TooLarge { limit } => FormatError::PayloadTooLarge { limit },
            BoundedReadError::Read(_) => FormatError::bad_request("request body could not be read"),
        })?;
        let parsed = self.pool.run(move || parse_metadata(&bytes)).await?;
        let metadata = match parsed {
            Ok(metadata) => metadata,
            Err(error) => {
                metrics::metadata_op("validate_upload", "refused");
                return Err(error.into());
            }
        };
        if !describes(level, &metadata) {
            metrics::metadata_op("validate_upload", "mismatch");
            return Err(FormatError::bad_request(
                "the metadata does not describe the artifact in its path",
            ));
        }
        metrics::metadata_op("validate_upload", "ok");
        Ok(status_only(StatusCode::CREATED))
    }

    /// `DELETE`: one file, or a whole version when the path ends in a slash.
    pub(crate) async fn hosted_delete(
        &self,
        cx: &FormatContext,
        req: &ArtifactRequest,
        parsed: Option<MavenPath>,
    ) -> Result<Response<Body>, FormatError> {
        if req.path.has_trailing_slash() {
            return delete_version(cx, req).await;
        }
        match parsed {
            Some(MavenPath::Artifact {
                file,
                checksum: None,
            }) => delete_file(cx, &file).await,
            // Generated and derived documents cannot be deleted: they follow the files.
            Some(_) => Err(FormatError::MethodNotAllowed {
                allow: "GET, HEAD, PUT",
            }),
            None => Err(FormatError::bad_request(
                "the path is not a Maven 2 repository layout path",
            )),
        }
    }
}

fn refuse_when_read_only(cx: &FormatContext) -> Result<(), FormatError> {
    if cx.repository().write_policy == rustryx_core::model::WritePolicy::Deny {
        return Err(FormatError::from(PolicyViolation::WritePolicy(
            rustryx_core::model::WritePolicy::Deny,
        )));
    }
    Ok(())
}

/// True when the uploaded document names what its path names (a missing name is not a mismatch).
fn describes(level: &MetadataLevel, metadata: &Metadata) -> bool {
    let (group, artifact, version) = match level {
        MetadataLevel::Group { group_id } => (group_id.clone(), None, None),
        MetadataLevel::Artifact {
            group_id,
            artifact_id,
        } => (group_id.clone(), Some(artifact_id.as_str()), None),
        MetadataLevel::Version {
            group_id,
            artifact_id,
            version,
        } => (
            group_id.clone(),
            Some(artifact_id.as_str()),
            Some(version.as_str()),
        ),
    };
    let same = |field: &Option<String>, expected: &str| {
        field.as_deref().is_none_or(|value| value == expected)
    };
    // A group level document sits at an `Artifact` path whose directory is the groupId.
    let group_level_document = metadata.artifact_id.is_none() && !metadata.plugins.is_empty();
    if group_level_document {
        let dotted = level.dir().replace('/', ".");
        return same(&metadata.group_id, &dotted);
    }
    same(&metadata.group_id, &group)
        && artifact.is_none_or(|a| same(&metadata.artifact_id, a))
        && version.is_none_or(|v| same(&metadata.version, v))
}

async fn put_artifact(
    cx: &FormatContext,
    req: &ArtifactRequest,
    file: &ArtifactPath,
    body: Body,
) -> Result<Response<Body>, FormatError> {
    enforce_write_policy(cx.repository(), &file.version)?;
    let mut spec = UploadSpec::from_request(req);
    spec.component = Some(ComponentSpec {
        group: Some(file.group_id.clone()),
        name: file.artifact_id.clone(),
        version: Some(file.version.clone()),
    });
    let outcome = cx.hosted().upload(spec, body).await?;
    Ok(upload_response(
        outcome.created(),
        &etag_from_checksums(&outcome.asset.checksums),
    ))
}

/// A supplied checksum is verified against the stored file and dropped (see `checksum`).
async fn put_artifact_checksum(
    cx: &FormatContext,
    req: &ArtifactRequest,
    file: &ArtifactPath,
    algo: ChecksumAlgo,
    body: Body,
) -> Result<Response<Body>, FormatError> {
    refuse_when_read_only(cx)?;
    enforce_write_policy(cx.repository(), &file.version)?;
    let supplied = read_checksum_file(req, body, algo).await?;
    let asset = cx
        .ports()
        .assets
        .get_by_path(cx.repository().id, &file.to_path_string())
        .await?
        .ok_or_else(|| {
            FormatError::conflict("the file this checksum describes has not been uploaded")
        })?;
    let actual = digest_of_asset(cx, &asset, algo).await?;
    if digests_equal(&supplied, &actual) {
        metrics::checksum_check("ok");
        return Ok(status_only(StatusCode::CREATED));
    }
    metrics::checksum_check("mismatch");
    audit::record(
        cx,
        req,
        AuditKind::SecurityDecision,
        "asset.rejected",
        "failure",
        serde_json::json!({ "reason": "checksum_mismatch", "algorithm": algo.suffix() }),
    )
    .await;
    Err(FormatError::DigestMismatch)
}

/// Reads and parses a checksum file body, at most [`MAX_CHECKSUM_FILE_BYTES`].
async fn read_checksum_file(
    req: &ArtifactRequest,
    body: Body,
    algo: ChecksumAlgo,
) -> Result<String, FormatError> {
    if req
        .head
        .content_length()
        .is_some_and(|declared| declared > MAX_CHECKSUM_FILE_BYTES)
    {
        return Err(FormatError::PayloadTooLarge {
            limit: MAX_CHECKSUM_FILE_BYTES,
        });
    }
    let bytes = read_bounded(body, MAX_CHECKSUM_FILE_BYTES)
        .await
        .map_err(|error| match error {
            BoundedReadError::TooLarge { limit } => FormatError::PayloadTooLarge { limit },
            BoundedReadError::Read(_) => FormatError::bad_request("request body could not be read"),
        })?;
    parse_checksum_file(&bytes, algo)
        .map_err(|_| FormatError::bad_request("the checksum file does not hold a hex digest"))
}

/// The digest of a stored file: from the row when the store computed it, streamed otherwise.
async fn digest_of_asset(
    cx: &FormatContext,
    asset: &Asset,
    algo: ChecksumAlgo,
) -> Result<String, FormatError> {
    if let Some(digest) = stored_digest(algo, &asset.checksums) {
        return Ok(digest);
    }
    let record = cx.ports().blobs.get(asset.blob_id).await?.ok_or_else(|| {
        FormatError::internal("asset references a blob record that does not exist")
    })?;
    let store = cx.store_for_blob(&record).await?;
    let read = store.get(&BlobKey::new(record.key), None).await?;
    Ok(sha512_of_stream(read.stream).await?)
}

async fn hosted_artifact(
    cx: &FormatContext,
    req: &ArtifactRequest,
    file: &ArtifactPath,
) -> Result<Response<Body>, FormatError> {
    match cx.hosted().download(req).await {
        Err(FormatError::NotFound) if is_pointer(file) => {
            let Some(stamped) = resolve_pointer(cx, file).await? else {
                return Err(FormatError::NotFound);
            };
            cx.hosted()
                .download(&with_path(req, &stamped.to_path_string())?)
                .await
        }
        other => other,
    }
}

async fn hosted_artifact_checksum(
    cx: &FormatContext,
    req: &ArtifactRequest,
    file: &ArtifactPath,
    algo: ChecksumAlgo,
) -> Result<Response<Body>, FormatError> {
    let asset = find_target(cx, file).await?.ok_or(FormatError::NotFound)?;
    let digest = digest_of_asset(cx, &asset, algo).await?;
    respond(&req.head, checksum_document(digest, Some(asset.updated_at)))
}

/// The asset a path names: the file itself, or for `artifact-1.0-SNAPSHOT.jar` the newest
/// timestamped build of it.
async fn find_target(
    cx: &FormatContext,
    file: &ArtifactPath,
) -> Result<Option<Asset>, FormatError> {
    let assets = &cx.ports().assets;
    let repository = cx.repository().id;
    if let Some(asset) = assets
        .get_by_path(repository, &file.to_path_string())
        .await?
    {
        return Ok(Some(asset));
    }
    if is_pointer(file)
        && let Some(stamped) = resolve_pointer(cx, file).await?
    {
        return Ok(assets
            .get_by_path(repository, &stamped.to_path_string())
            .await?);
    }
    Ok(None)
}

/// A snapshot file named without a timestamp: what a Maven 2 client with `uniqueVersion=false`
/// writes and what a client without the metadata asks for.
fn is_pointer(file: &ArtifactPath) -> bool {
    file.is_snapshot() && file.stamp.is_none()
}

/// The newest timestamped build with the same classifier and extension.
///
/// The build read differs from the path that was authorized, but only in the stamp: the group,
/// artifact, version, classifier and extension are those of the request, so every content
/// selector over the coordinate decides the same (a selector on the exact path of the pointer
/// is the one case that does not, and it is documented in `docs/format-maven.md`).
async fn resolve_pointer(
    cx: &FormatContext,
    file: &ArtifactPath,
) -> Result<Option<ArtifactPath>, FormatError> {
    let builds = list_builds(cx, &file.group_id, &file.artifact_id, &file.version).await?;
    let newest = builds
        .into_iter()
        .filter(|(build, _)| {
            build.classifier == file.classifier && build.extension == file.extension
        })
        .map(|(build, _)| build.stamp)
        .max();
    metrics::metadata_op(
        "snapshot_resolve",
        if newest.is_some() { "ok" } else { "not_found" },
    );
    Ok(newest.map(|stamp| file.with_stamp(stamp)))
}

async fn hosted_metadata(
    cx: &FormatContext,
    req: &ArtifactRequest,
    level: &MetadataLevel,
    checksum: Option<ChecksumAlgo>,
) -> Result<Response<Body>, FormatError> {
    let generated = match level {
        MetadataLevel::Artifact {
            group_id,
            artifact_id,
        } => {
            let components = components_of(cx, group_id, artifact_id).await?;
            let records: Vec<VersionRecord> = components
                .iter()
                .filter_map(|component| {
                    Some(VersionRecord {
                        version: component.version.clone()?,
                        changed: component.created_at.max(component.updated_at),
                    })
                })
                .collect();
            let modified = records.iter().map(|r| r.changed).max();
            generate_artifact_metadata(group_id, artifact_id, &records).zip(modified)
        }
        MetadataLevel::Version {
            group_id,
            artifact_id,
            version,
        } => {
            let builds = list_builds(cx, group_id, artifact_id, version).await?;
            let modified = builds.iter().map(|(_, changed)| *changed).max();
            let assets: Vec<BuildAsset> = builds.into_iter().map(|(build, _)| build).collect();
            generate_version_metadata(group_id, artifact_id, version, &assets).zip(modified)
        }
        // Plugin prefixes are not derivable from components: a hosted repository has none.
        MetadataLevel::Group { .. } => None,
    };
    let Some((metadata, modified)) = generated else {
        metrics::metadata_op("generate", "not_found");
        return Err(FormatError::NotFound);
    };
    metrics::metadata_op("generate", "ok");
    let xml = write_metadata(&metadata);
    match checksum {
        None => respond(&req.head, Document::new(xml, XML).modified(Some(modified))),
        Some(algo) => respond(
            &req.head,
            checksum_document(digest_of_bytes(algo, xml.as_bytes()), Some(modified)),
        ),
    }
}

/// Every component of one artifact, page by page.
async fn components_of(
    cx: &FormatContext,
    group_id: &str,
    artifact_id: &str,
) -> Result<Vec<Component>, FormatError> {
    let filter = ComponentFilter {
        repository_id: Some(cx.repository().id),
        group_id: Some(group_id.to_owned()),
        name: Some(artifact_id.to_owned()),
        ..ComponentFilter::default()
    };
    let mut items = Vec::new();
    let mut after = None;
    for _ in 0..MAX_PAGES {
        let page = cx
            .ports()
            .components
            .list(&filter, &PageRequest { limit: PAGE, after })
            .await?;
        items.extend(page.items);
        if items.len() > MAX_LISTED {
            return Err(FormatError::internal(
                "an artifact has too many versions to list",
            ));
        }
        match page.next {
            Some(next) => after = Some(next),
            None => return Ok(items),
        }
    }
    Err(FormatError::internal("the component listing did not end"))
}

/// The timestamped files of one snapshot version with the time each last changed.
async fn list_builds(
    cx: &FormatContext,
    group_id: &str,
    artifact_id: &str,
    version: &str,
) -> Result<Vec<(BuildAsset, OffsetDateTime)>, FormatError> {
    let level = MetadataLevel::Version {
        group_id: group_id.to_owned(),
        artifact_id: artifact_id.to_owned(),
        version: version.to_owned(),
    };
    let prefix = format!("{}/", level.dir());
    let mut builds = Vec::new();
    let mut after = None;
    for _ in 0..MAX_PAGES {
        let page = cx
            .ports()
            .assets
            .list(
                cx.repository().id,
                &prefix,
                &PageRequest { limit: PAGE, after },
            )
            .await?;
        for asset in page.items {
            if let Ok(MavenPath::Artifact {
                file,
                checksum: None,
            }) = MavenPath::parse(&asset.path)
                && let Some(stamp) = file.stamp
                && file.version == version
            {
                builds.push((
                    BuildAsset {
                        classifier: file.classifier,
                        extension: file.extension,
                        stamp,
                    },
                    asset.updated_at,
                ));
            }
        }
        match page.next {
            Some(next) => after = Some(next),
            None => return Ok(builds),
        }
    }
    Err(FormatError::internal("the asset listing did not end"))
}

fn write_options(cx: &FormatContext, req: &ArtifactRequest) -> WriteOptions {
    let options = WriteOptions::new().with_actor(ActorRef::of(cx.principal()));
    match req.head.client.request_id.as_deref() {
        Some(id) => options.with_request_id(id),
        None => options,
    }
}

/// Deletes one file. A component that loses its last file is removed too, otherwise the
/// generated version list would still name a version nothing can be downloaded from.
async fn delete_file(
    cx: &FormatContext,
    file: &ArtifactPath,
) -> Result<Response<Body>, FormatError> {
    let path = rustryx_format_core::NormalizedPath::parse(&file.to_path_string())?;
    let component = cx
        .ports()
        .assets
        .get_by_path(cx.repository().id, path.as_str())
        .await?
        .ok_or(FormatError::NotFound)?
        .component_id;
    cx.hosted().delete(&path).await?;
    if let Some(id) = component {
        let remaining = cx.ports().assets.list_by_component(id).await?;
        if remaining.is_empty() {
            // Another request may have removed it between the two calls: that is the result we want.
            match cx
                .ports()
                .components
                .delete_checked(
                    id,
                    &WriteOptions::new().with_actor(ActorRef::of(cx.principal())),
                )
                .await
            {
                Ok(()) | Err(MutationError::Store(StoreError::NotFound(_))) => {}
                Err(error) => return Err(error.into()),
            }
        }
    }
    Ok(status_only(StatusCode::NO_CONTENT))
}

/// Deletes a version with all its files in one step: the component port deletes the row and the
/// assets in one transaction under the immutability and hold guards, so a refusal leaves the
/// version whole.
async fn delete_version(
    cx: &FormatContext,
    req: &ArtifactRequest,
) -> Result<Response<Body>, FormatError> {
    let (group, artifact, version) = parse_version_dir(req.path.as_str())
        .map_err(|_| FormatError::bad_request("the path is not a version directory"))?;
    let repository = cx.repository();
    let mut coordinate = NewComponent::new(repository.id, RepoFormat::Maven2, artifact);
    coordinate.group_id = Some(group);
    coordinate.version = Some(version.clone());
    let component = cx
        .ports()
        .components
        .find(&coordinate)
        .await?
        .ok_or(FormatError::NotFound)?;
    let files = cx.ports().assets.list_by_component(component.id).await?;
    cx.ports()
        .components
        .delete_checked(component.id, &write_options(cx, req))
        .await?;
    audit::record(
        cx,
        req,
        AuditKind::ContentChange,
        "component.delete",
        "success",
        serde_json::json!({ "version": version, "files": files.len() }),
    )
    .await;
    Ok(status_only(StatusCode::NO_CONTENT))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn metadata(group: Option<&str>, artifact: Option<&str>, version: Option<&str>) -> Metadata {
        Metadata {
            group_id: group.map(str::to_owned),
            artifact_id: artifact.map(str::to_owned),
            version: version.map(str::to_owned),
            ..Metadata::default()
        }
    }

    fn artifact_level() -> MetadataLevel {
        MetadataLevel::Artifact {
            group_id: "org.acme".into(),
            artifact_id: "lib".into(),
        }
    }

    #[test]
    fn an_uploaded_document_must_name_what_its_path_names() {
        assert!(describes(
            &artifact_level(),
            &metadata(Some("org.acme"), Some("lib"), None)
        ));
        assert!(describes(&artifact_level(), &metadata(None, None, None)));
        assert!(!describes(
            &artifact_level(),
            &metadata(Some("org.evil"), Some("lib"), None)
        ));
        assert!(!describes(
            &artifact_level(),
            &metadata(Some("org.acme"), Some("other"), None)
        ));
        let version = MetadataLevel::Version {
            group_id: "org.acme".into(),
            artifact_id: "lib".into(),
            version: "1.0-SNAPSHOT".into(),
        };
        assert!(describes(
            &version,
            &metadata(Some("org.acme"), Some("lib"), Some("1.0-SNAPSHOT"))
        ));
        assert!(!describes(
            &version,
            &metadata(Some("org.acme"), Some("lib"), Some("2.0-SNAPSHOT"))
        ));
    }

    #[test]
    fn a_plugin_document_names_the_directory_as_its_group() {
        let level = MetadataLevel::Artifact {
            group_id: "org.apache.maven".into(),
            artifact_id: "plugins".into(),
        };
        let mut document = metadata(Some("org.apache.maven.plugins"), None, None);
        document.plugins.push(crate::metadata::Plugin {
            name: None,
            prefix: "clean".into(),
            artifact_id: "maven-clean-plugin".into(),
        });
        assert!(describes(&level, &document));
        document.group_id = Some("org.other".into());
        assert!(!describes(&level, &document));
    }
}
