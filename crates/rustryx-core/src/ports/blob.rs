//! Blob store port.
//!
//! A blob store holds immutable objects under opaque keys. Writes are streamed:
//! the caller pushes chunks into a [`BlobWriter`], which hashes them on the fly,
//! and the object becomes visible only at [`BlobWriter::commit`]. Nothing is
//! ever read into memory as a whole.

use std::time::Duration;

use async_trait::async_trait;
use bytes::Bytes;
use futures::stream::BoxStream;
use time::OffsetDateTime;

use crate::error::BlobError;
use crate::ids::BlobStoreId;
use crate::model::{BlobStoreKind, Checksums};
use crate::secret::Secret;

/// Opaque object key. Generated by the caller (`UUIDv7` text) so that a new
/// version of an artifact never overwrites the bytes of the old one.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct BlobKey(String);

impl BlobKey {
    /// Wraps a key string. Implementations must reject keys that could escape
    /// their root (`..`, absolute paths, NUL) when they use them as paths.
    #[must_use]
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// Borrows the key.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Inclusive byte range for partial reads.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ByteRange {
    /// First byte.
    pub start: u64,
    /// Last byte (inclusive). `None` means to the end.
    pub end: Option<u64>,
}

/// What a store knows about an object without reading it: its size and, when the store
/// reports one, its modification time. Digests are NOT known: S3 returns no SHA-256 on `HEAD`
/// and the object name is opaque, so the digests live in the `blobs` row.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct BlobMeta {
    /// Size in bytes.
    pub size_bytes: u64,
    /// Modification time, when the store reports it. The staging sweep and `verify_blobs`
    /// use it to tell a fresh object from a leak.
    pub modified: Option<OffsetDateTime>,
}

impl BlobMeta {
    /// Metadata with a size and no modification time.
    #[must_use]
    pub const fn new(size_bytes: u64) -> Self {
        Self {
            size_bytes,
            modified: None,
        }
    }
}

/// An open read. The stream must be backpressured: it yields the next chunk
/// only when polled.
pub struct BlobRead {
    /// Full object size (not the range size).
    pub total_size: u64,
    /// Content, chunked.
    pub stream: BoxStream<'static, Result<Bytes, BlobError>>,
}

impl std::fmt::Debug for BlobRead {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("BlobRead")
            .field("total_size", &self.total_size)
            .finish_non_exhaustive()
    }
}

/// Outcome of a committed write.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct BlobCommit {
    /// Bytes written.
    pub size_bytes: u64,
    /// Digests of exactly the bytes written, computed incrementally.
    pub checksums: Checksums,
    /// The member store that took the bytes, `None` for a plain store. The pipeline stores it
    /// as `BlobRecord::blob_store_id`, so a blob row always names the concrete store.
    pub placement: Option<BlobStoreId>,
}

impl BlobCommit {
    /// A commit of a plain store (no placement).
    #[must_use]
    pub const fn new(size_bytes: u64, checksums: Checksums) -> Self {
        Self {
            size_bytes,
            checksums,
            placement: None,
        }
    }
}

/// What a store can do, so that callers distinguish "none" from "cannot tell".
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[non_exhaustive]
#[allow(
    clippy::struct_excessive_bools,
    reason = "a capability set is one flag per capability by definition"
)]
pub struct BlobStoreCapabilities {
    /// `list_stale_staging` can really list (an empty answer then means "none").
    pub lists_staging: bool,
    /// `list_keys` is implemented.
    pub lists_keys: bool,
    /// `presign_get` can return a URL.
    pub can_presign: bool,
    /// `resumable` returns a store.
    pub resumable: bool,
}

/// A page of keys for reconciliation (`verify_blobs`).
#[derive(Debug, Clone)]
pub struct KeyPage {
    /// Keys with their metadata.
    pub keys: Vec<(BlobKey, BlobMeta)>,
    /// Opaque cursor of the next page, `None` on the last page.
    pub next: Option<String>,
}

/// Response headers a presigned download should carry.
#[derive(Debug, Clone, Default)]
pub struct PresignOptions {
    /// `response-content-type`.
    pub response_content_type: Option<String>,
    /// Always `attachment; filename=...` for active content types.
    pub response_content_disposition: Option<String>,
}

/// A time limited direct download URL.
#[derive(Debug, Clone)]
pub struct PresignedUrl {
    /// A bearer capability. Never logged, never stored, never put in an audit row. Redacted in
    /// `Debug`.
    pub url: Secret,
    /// When the URL stops working.
    pub expires_at: OffsetDateTime,
}

/// Longest upload handle, in bytes.
pub const MAX_UPLOAD_HANDLE_LEN: usize = 128;

/// Opaque handle of a resumable upload: 1 to 128 bytes of URL safe characters (`A-Z a-z 0-9 . _ ~ -`).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct UploadHandle(String);

impl UploadHandle {
    /// Wraps a handle that a client sent back. A malformed handle cannot name an upload, so
    /// the error is `NotFound` (the OCI answer is "upload unknown").
    ///
    /// # Errors
    /// Returns [`BlobError::NotFound`] for an empty, oversized or not URL safe value.
    pub fn new(value: impl Into<String>) -> Result<Self, BlobError> {
        let value = value.into();
        let url_safe = value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'~' | b'-'));
        if value.is_empty() || value.len() > MAX_UPLOAD_HANDLE_LEN || !url_safe {
            return Err(BlobError::NotFound);
        }
        Ok(Self(value))
    }

    /// Borrows the handle.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// A blob store (local directory, S3-compatible bucket, Azure container or a group).
#[async_trait]
pub trait BlobStore: Send + Sync + 'static {
    /// Kind of this store.
    fn kind(&self) -> BlobStoreKind;

    /// Starts a streamed write to `key`.
    ///
    /// `size_hint` lets S3 pick a part size. The object is invisible until
    /// `commit`. Cancel safe: dropping the writer without commit discards the
    /// data (implementations clean up on drop or in the next GC pass).
    async fn begin(
        &self,
        key: &BlobKey,
        size_hint: Option<u64>,
    ) -> Result<Box<dyn BlobWriter>, BlobError>;

    /// Opens a read. Cancel safe.
    ///
    /// Errors: `NotFound`, `RangeNotSatisfiable`, `Unavailable`.
    async fn get(&self, key: &BlobKey, range: Option<ByteRange>) -> Result<BlobRead, BlobError>;

    /// Reports whether the object exists and its size. Cancel safe.
    async fn head(&self, key: &BlobKey) -> Result<Option<BlobMeta>, BlobError>;

    /// Deletes the object. Deleting a missing key succeeds. Cancel safe.
    async fn delete(&self, key: &BlobKey) -> Result<(), BlobError>;

    /// Lists keys that were left in staging (aborted uploads) older than
    /// `min_age`, for the GC job to delete. Cancel safe.
    ///
    /// A store that cannot list them says so through `capabilities().lists_staging`; an empty
    /// answer from such a store means "cannot tell", not "none".
    async fn list_stale_staging(&self, min_age: Duration) -> Result<Vec<BlobKey>, BlobError>;

    /// Cheap reachability check used by the status API (not by `/readyz`).
    async fn health(&self) -> Result<(), BlobError>;

    /// What this store can do. Default: nothing optional.
    fn capabilities(&self) -> BlobStoreCapabilities {
        BlobStoreCapabilities::default()
    }

    /// Releases background work (aborts tasks). Idempotent. Default no-op.
    async fn shutdown(&self) {}

    /// Lists committed keys after the opaque cursor `after`, at most `limit`, in a stable,
    /// store defined order (the local layout shards by a hash of the key, so key order is not
    /// promised and no caller may rely on it). Cancel safe.
    ///
    /// Default `Err(Unsupported("list_keys"))`: a caller must not read an unsupported listing
    /// as an empty store.
    async fn list_keys(&self, _after: Option<&str>, _limit: u32) -> Result<KeyPage, BlobError> {
        Err(BlobError::Unsupported("list_keys"))
    }

    /// A time limited direct download URL, or `Ok(None)` when the store has none (local) or
    /// presigning is not enabled for it. Cancel safe. Default `Ok(None)`.
    async fn presign_get(
        &self,
        _key: &BlobKey,
        _ttl: Duration,
        _options: &PresignOptions,
    ) -> Result<Option<PresignedUrl>, BlobError> {
        Ok(None)
    }

    /// Contract for chunked uploads that span requests and nodes. Default `None`.
    fn resumable(&self) -> Option<&dyn ResumableBlobStore> {
        None
    }
}

/// Chunked upload across requests.
///
/// Each chunk is staged as its own object, so a chunk may be any size. `finalize` streams the
/// chunks in order through a normal writer, which hashes the content and commits it. It reads
/// every chunk once more: a SHA-256 state cannot be moved between nodes, and S3 parts under
/// 5 MiB are illegal, so composing server side is not an option. Monolithic uploads do not use
/// this.
#[async_trait]
pub trait ResumableBlobStore: Send + Sync {
    /// Starts an upload. The handle is opaque and URL safe. Cancel safe: a handle that was
    /// never returned names nothing.
    async fn begin_resumable(&self, key: &BlobKey) -> Result<UploadHandle, BlobError>;

    /// Stages the chunk that starts at `offset`. An offset that is not the current length is
    /// `RangeNotSatisfiable` (the client resumes from the reported length). Not cancel safe
    /// for the handle: after a cancelled call the caller re-reads `length`.
    async fn append(
        &self,
        handle: &UploadHandle,
        offset: u64,
        chunk: Bytes,
    ) -> Result<(), BlobError>;

    /// Bytes staged so far. Cancel safe.
    async fn length(&self, handle: &UploadHandle) -> Result<u64, BlobError>;

    /// Joins, hashes and commits. Abandoned handles are removed by the staging sweep after
    /// `gc.min_age_secs`. Not cancel safe: if cancelled, the object may or may not be visible,
    /// so the caller must not publish metadata for it.
    async fn finalize(&self, handle: UploadHandle) -> Result<BlobCommit, BlobError>;

    /// Discards the staged chunks. Idempotent.
    async fn abort(&self, handle: UploadHandle) -> Result<(), BlobError>;
}

/// An in-progress streamed write.
#[async_trait]
pub trait BlobWriter: Send {
    /// Appends a chunk. Implementations feed SHA-1, SHA-256 and MD5 in slices of
    /// at most 64 KiB in the calling task. Backpressure: the future completes
    /// when the chunk was accepted. Not cancel safe for the writer: after a
    /// cancelled `write` the writer must be aborted, not reused.
    async fn write(&mut self, chunk: Bytes) -> Result<(), BlobError>;

    /// Makes the object visible atomically and returns size and digests.
    /// Not cancel safe: if cancelled, the object may or may not be visible, so
    /// the caller must not publish metadata for it.
    async fn commit(self: Box<Self>) -> Result<BlobCommit, BlobError>;

    /// Discards everything written so far. Idempotent.
    async fn abort(self: Box<Self>) -> Result<(), BlobError>;
}

#[cfg(test)]
mod tests {
    use futures::executor::block_on;

    use super::*;
    use crate::testing::at;

    struct Bare;

    #[async_trait]
    impl BlobStore for Bare {
        fn kind(&self) -> BlobStoreKind {
            BlobStoreKind::Local
        }
        async fn begin(
            &self,
            _: &BlobKey,
            _: Option<u64>,
        ) -> Result<Box<dyn BlobWriter>, BlobError> {
            Err(BlobError::Unavailable("test".into()))
        }
        async fn get(&self, _: &BlobKey, _: Option<ByteRange>) -> Result<BlobRead, BlobError> {
            Err(BlobError::NotFound)
        }
        async fn head(&self, _: &BlobKey) -> Result<Option<BlobMeta>, BlobError> {
            Ok(None)
        }
        async fn delete(&self, _: &BlobKey) -> Result<(), BlobError> {
            Ok(())
        }
        async fn list_stale_staging(&self, _: Duration) -> Result<Vec<BlobKey>, BlobError> {
            Ok(Vec::new())
        }
        async fn health(&self) -> Result<(), BlobError> {
            Ok(())
        }
    }

    #[test]
    fn a_store_that_implements_only_the_required_methods_has_safe_defaults() {
        let store = Bare;
        assert_eq!(store.capabilities(), BlobStoreCapabilities::default());
        assert!(store.resumable().is_none());
        block_on(async {
            store.shutdown().await;
            store.shutdown().await;
            let key = BlobKey::new("k");
            assert!(
                store
                    .presign_get(&key, Duration::from_secs(60), &PresignOptions::default())
                    .await
                    .expect("ok")
                    .is_none()
            );
        });
    }

    #[test]
    fn must_not_read_an_unsupported_listing_as_an_empty_store() {
        let outcome = block_on(Bare.list_keys(None, 100));
        assert!(matches!(outcome, Err(BlobError::Unsupported("list_keys"))));
    }

    #[test]
    fn capabilities_default_to_none() {
        let caps = BlobStoreCapabilities::default();
        assert!(!caps.lists_staging && !caps.lists_keys && !caps.can_presign && !caps.resumable);
    }

    #[test]
    fn meta_and_commit_constructors_leave_the_optional_fields_empty() {
        let meta = BlobMeta::new(7);
        assert_eq!(meta.size_bytes, 7);
        assert!(meta.modified.is_none());
        let commit = BlobCommit::new(
            7,
            Checksums {
                sha1: "a".into(),
                sha256: "b".into(),
                md5: "c".into(),
            },
        );
        assert_eq!(commit.size_bytes, 7);
        assert!(commit.placement.is_none());
    }

    #[test]
    fn must_not_leak_a_presigned_url_through_debug() {
        let url = PresignedUrl {
            url: Secret::new("https://bucket.example.org/k?X-Amz-Signature=canary-signature"),
            expires_at: at(),
        };
        let text = format!("{url:?}");
        assert!(!text.contains("canary-signature"), "{text}");
        assert!(!text.contains("X-Amz"), "{text}");
    }

    #[test]
    fn upload_handles_are_url_safe_and_bounded() {
        for ok in [
            "a",
            "0123-abcd_EFGH.~",
            &"h".repeat(128),
            "018f3c1e-7b2a-7c00-8000-0123456789ab",
        ] {
            assert_eq!(UploadHandle::new(ok).expect("valid").as_str(), ok);
        }
        for bad in [
            "",
            "a b",
            "a/b",
            "a?b",
            "a%2fb",
            "é",
            "a\n",
            &"h".repeat(129),
        ] {
            assert!(
                matches!(UploadHandle::new(bad), Err(BlobError::NotFound)),
                "{bad:?}"
            );
        }
    }

    #[test]
    fn debug_of_a_read_does_not_print_the_stream() {
        let read = BlobRead {
            total_size: 3,
            stream: Box::pin(futures::stream::empty()),
        };
        let text = format!("{read:?}");
        assert!(text.contains("total_size: 3"));
    }
}
